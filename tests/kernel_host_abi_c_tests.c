static uint64_t fnv1a_64(const char* text) {
    uint64_t hash = UINT64_C(14695981039346656037);
    while (*text != '\0') {
        hash ^= (uint64_t)(unsigned char)(*text);
        hash *= UINT64_C(1099511628211);
        ++text;
    }
    return hash;
}

