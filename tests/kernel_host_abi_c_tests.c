typedef struct CallbackGcContext {
    const RsHostApiV1* api;
    RsHeapHandleV1 heap;
    int64_t scale_factor;
    int invoked;
    int active_obj_survived_gc;
    int unpinned_garbage_collected;
} CallbackGcContext;

static RsStatusV1 c_host_scale_and_gc_callback(
    void* user_data,
    const RsValueV1* args,
    uint32_t arg_count,
    RsValueV1* out_result) {
    CallbackGcContext* ctx = (CallbackGcContext*)user_data;
    if (ctx == NULL || args == NULL || arg_count != 2 || out_result == NULL) {
        return RS_STATUS_V1_INVALID_ARGUMENT;
    }
    if (args[0].kind != RS_VALUE_KIND_V1_INT64 ||
        args[1].kind != RS_VALUE_KIND_V1_OBJECT_REF) {
        return RS_STATUS_V1_INVALID_ARGUMENT;
    }

    ++ctx->invoked;
    const RsObjectRefV1 active_unit_ref = args[1].payload.obj_ref;

    /* Allocate unpinned temporary garbage string on the VM heap and verify GC sweeps it
     * WITHOUT sweeping `active_unit_ref` (which is rooted on VM's active ShadowStack). */
    RsObjectRefV1 temp_trash = {0};
    if (ctx->api->string_alloc_utf8(ctx->heap, "ephemeral-trash", 15u, &temp_trash) != RS_STATUS_V1_OK) {
        return RS_STATUS_V1_RUNTIME_ERROR;
    }
    const RsWeakRefV1 weak_trash = ctx->api->weak_from_object(temp_trash);
    RsObjectRefV1 resolved_before = {0};
    if (ctx->api->weak_try_resolve(ctx->heap, weak_trash, &resolved_before) != RS_STATUS_V1_OK) {
        return RS_STATUS_V1_RUNTIME_ERROR;
    }

    if (ctx->api->heap_collect(ctx->heap) != RS_STATUS_V1_OK) {
        return RS_STATUS_V1_RUNTIME_ERROR;
    }
    uint8_t budget_completed = 0;
    if (ctx->api->heap_collect_budget_ns(ctx->heap, UINT64_C(5000000), &budget_completed) != RS_STATUS_V1_OK) {
        return RS_STATUS_V1_RUNTIME_ERROR;
    }

    RsObjectRefV1 resolved_after = {0};
    ctx->unpinned_garbage_collected =
        (ctx->api->weak_try_resolve(ctx->heap, weak_trash, &resolved_after) == RS_STATUS_V1_STALE_REFERENCE)
            ? 1
            : 0;
    ctx->active_obj_survived_gc =
        (ctx->api->heap_is_alive(ctx->heap, active_unit_ref) == 1u) ? 1 : 0;

    if (!ctx->active_obj_survived_gc) {
        return RS_STATUS_V1_STALE_REFERENCE;
    }

    /* Read active VM stack object field safely after GC */
    RsValueV1 label_val = {0};
    if (ctx->api->heap_read_field_with_policy(
            ctx->heap,
            ctx->heap,
            active_unit_ref,
            1u,
            RS_CROSS_HEAP_V1_ALLOW_READ_WRITE,
            &label_val) != RS_STATUS_V1_OK ||
        label_val.kind != RS_VALUE_KIND_V1_OBJECT_REF) {
        return RS_STATUS_V1_RUNTIME_ERROR;
    }

    const char* utf8_ptr = NULL;
    size_t utf8_len = 0;
    if (ctx->api->string_read_utf8(
            ctx->heap, label_val.payload.obj_ref, &utf8_ptr, &utf8_len) != RS_STATUS_V1_OK ||
        utf8_len != 10u ||
        memcmp(utf8_ptr, "alive-unit", 10u) != 0) {
        return RS_STATUS_V1_RUNTIME_ERROR;
    }

    out_result->kind = RS_VALUE_KIND_V1_INT64;
    out_result->payload.i64_val = args[0].payload.i64_val * ctx->scale_factor;
    return RS_STATUS_V1_OK;
}

